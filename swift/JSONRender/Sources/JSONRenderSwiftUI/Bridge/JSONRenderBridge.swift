import Foundation
import JavaScriptCore

/// Typed access to the bundled `@json-render/swift` JavaScript (catalog, prompts,
/// spec validation and the JSONL stream compiler) running in JavaScriptCore.
///
/// All JavaScript of every bridge instance runs on one shared serial queue (the actors'
/// executor), so JavaScriptCore is never used concurrently, not even across contexts.
/// JavaScript exceptions surface as ``JSONRenderBridgeError/javaScript(message:stack:)``.
public actor JSONRenderBridge {
    /// The single queue all JavaScriptCore work runs on.
    private static let queue = DispatchSerialQueue(label: "JSONRenderBridge.JavaScriptCore")

    /// One JavaScriptCore virtual machine (one heap and collector) shared by every bridge.
    /// Only touched on ``queue``, which is what makes the unchecked sendability sound.
    private final class SharedVM: @unchecked Sendable {
        let machine = JSVirtualMachine()
    }

    private static let sharedVM = SharedVM()

    public nonisolated var unownedExecutor: UnownedSerialExecutor {
        Self.queue.asUnownedSerialExecutor()
    }

    /// Which catalog a call targets, by its name in the bridge script.
    ///
    /// The bundled script has ``swiftui`` and ``pdf``. A script built with `installBridge({ catalogs })`
    /// from `@json-render/swift/bridge` (loaded with ``init(script:sourceURL:)``) adds its own names:
    ///
    /// ```swift
    /// extension JSONRenderBridge.Catalog {
    ///     static let database: Self = "database"
    /// }
    /// ```
    ///
    /// A name the script doesn't know throws ``JSONRenderBridgeError/javaScript(message:stack:)``
    /// (`Unknown catalog: …`).
    ///
    /// This used to be an enum. `allCases`, `init?(rawValue:)`, `.swiftui` and `.pdf` still work;
    /// an exhaustive `switch` over it now needs a `default` case.
    public struct Catalog: RawRepresentable, Hashable, Sendable, CaseIterable, ExpressibleByStringLiteral {
        public var rawValue: String

        /// Never fails; failable so code written for the former enum (`if let`, `!`) still compiles.
        public init?(rawValue: String) {
            self.init(rawValue)
        }

        public init(_ rawValue: String) {
            self.rawValue = rawValue
        }

        public init(stringLiteral value: String) {
            self.init(value)
        }

        /// SwiftUI forms (`@json-render/swift`).
        public static let swiftui = Self("swiftui")
        /// Documents (`@json-render/react-pdf` standard components).
        public static let pdf = Self("pdf")

        /// The built-in catalogs only, `[.swiftui, .pdf]`: catalogs a custom script adds aren't
        /// known on the Swift side.
        public static let allCases: [Self] = [.swiftui, .pdf]
    }

    public enum PromptMode: String, Sendable {
        /// The model outputs only JSONL patches.
        case standalone
        /// The model may write prose with patches in a ```spec fence.
        case inline
    }

    private let context: JSContext
    private let api: JSValue

    /// Loads `json-render-bridge.js` from the package bundle.
    public init() throws {
        guard let url = Bundle.module.url(forResource: "json-render-bridge", withExtension: "js") else {
            throw JSONRenderBridgeError.resourceMissing
        }
        try self.init(script: String(contentsOf: url, encoding: .utf8), sourceURL: url)
    }

    /// Evaluates a custom bridge script (must install `globalThis.JSONRenderBridge`).
    public init(script: String, sourceURL: URL? = nil) throws {
        let (context, api) = try Self.queue.sync { () throws -> (JSContext, JSValue) in
            guard let machine = Self.sharedVM.machine, let context = JSContext(virtualMachine: machine) else {
                throw JSONRenderBridgeError.bridgeUnavailable
            }
            context.name = "JSONRenderBridge"
            context.evaluateScript(script, withSourceURL: sourceURL)
            if let exception = context.exception {
                throw JSONRenderBridgeError(exception: exception)
            }
            guard let api = context.objectForKeyedSubscript("JSONRenderBridge"), api.isObject else {
                throw JSONRenderBridgeError.bridgeUnavailable
            }
            return (context, api)
        }
        self.context = context
        self.api = api
    }

    // MARK: API

    public func version() throws -> String {
        try invoke("version").stringValue ?? ""
    }

    /// The system prompt generated by `catalog.prompt()`.
    public func systemPrompt(
        customRules: [String] = [], mode: PromptMode = .standalone, catalog: Catalog = .swiftui
    ) throws -> String {
        var options: [String: JSONValue] = ["mode": .string(mode.rawValue), "catalog": .string(catalog.rawValue)]
        if !customRules.isEmpty { options["customRules"] = .array(customRules.map(JSONValue.string)) }
        return try invoke("systemPrompt", .object(options)).stringValue ?? ""
    }

    /// Core `buildUserPrompt`; pass `currentSpec` (and `state`) to ask for edits.
    public func buildUserPrompt(
        _ prompt: String,
        currentSpec: Spec? = nil,
        state: JSONValue? = nil,
        maxPromptLength: Int? = nil
    ) throws -> String {
        var input: [String: JSONValue] = ["prompt": .string(prompt)]
        if let currentSpec { input["currentSpec"] = currentSpec.json }
        if let state { input["state"] = state }
        if let maxPromptLength { input["maxPromptLength"] = .number(Double(maxPromptLength)) }
        return try invoke("buildUserPrompt", .object(input)).stringValue ?? ""
    }

    public func catalogManifest(catalog: Catalog = .swiftui) throws -> CatalogManifest {
        try invoke("catalogManifest", Self.options(catalog)).decoded(as: CatalogManifest.self)
    }

    public func jsonSchema(strict: Bool = false, catalog: Catalog = .swiftui) throws -> JSONValue {
        try invoke("jsonSchema", .object(["strict": .bool(strict), "catalog": .string(catalog.rawValue)]))
    }

    private static func options(_ catalog: Catalog) -> JSONValue {
        .object(["catalog": .string(catalog.rawValue)])
    }

    /// Structural + catalog validation (core `validateSpec` and the catalog's Zod schemas).
    /// - Parameters:
    ///   - hostActions: action names the host registers; they are not reported as unknown.
    ///   - hostValidators: custom check types the host registers (``FormSession/validators``);
    ///     they are not reported as unknown.
    public func validateSpec(
        _ spec: Spec, hostActions: Set<String> = [], hostValidators: Set<String> = [], catalog: Catalog = .swiftui
    ) throws -> SpecValidation {
        let options: JSONValue = [
            "catalog": .string(catalog.rawValue),
            "hostActions": .array(hostActions.sorted().map(JSONValue.string)),
            "hostValidators": .array(hostValidators.sorted().map(JSONValue.string)),
        ]
        var validation = try invoke("validateSpec", spec.json, options).decoded(as: SpecValidation.self)
        // Also filter locally, so older bundles without the options behave the same.
        if !hostActions.isEmpty {
            validation.issues.removeAll { issue in
                guard issue.code == "unknown_action", let path = issue.path,
                      case .string(let action)? = spec.json.value(at: path) else { return false }
                return hostActions.contains(action)
            }
        }
        return validation
    }

    /// Core `autoFixSpec` (moves misplaced `visible`/`on`/`watch` out of props, etc.).
    public func autoFixSpec(_ spec: Spec, catalog: Catalog = .swiftui) throws -> Spec {
        Spec(json: try invoke("autoFixSpec", spec.json, Self.options(catalog)))
    }

    /// Creates a JSONL patch stream compiler (core `createSpecStreamCompiler`).
    public func makeStreamCompiler(initial: Spec? = nil) throws -> SpecStreamCompiler {
        guard let handle = try invoke("createCompiler", initial?.json ?? .null).intValue else {
            throw JSONRenderBridgeError.invalidResponse("createCompiler did not return a handle")
        }
        return SpecStreamCompiler(bridge: self, handle: handle)
    }

    func compilerPush(handle: Int, chunk: String) throws -> SpecStreamCompiler.Update {
        let result = try invoke("compilerPush", .number(Double(handle)), .string(chunk))
        return SpecStreamCompiler.Update(
            spec: Spec(json: result["spec"] ?? .object([:])),
            newPatches: result["newPatches"]?.arrayValue ?? []
        )
    }

    func compilerFinish(handle: Int) throws -> Spec {
        Spec(json: try invoke("compilerFinish", .number(Double(handle))))
    }

    func compilerDispose(handle: Int) throws {
        _ = try invoke("compilerDispose", .number(Double(handle)))
    }

    // MARK: Invocation

    /// Calls `JSONRenderBridge.invoke(method, argsJSON)`, which returns
    /// `{"result": …}` or `{"error": {"message", "stack"}}` as a JSON string.
    private func invoke(_ method: String, _ arguments: JSONValue...) throws -> JSONValue {
        let argsJSON = JSONValue.array(arguments).jsonString()
        let returned = api.invokeMethod("invoke", withArguments: [method, argsJSON])
        if let exception = context.exception {
            context.exception = nil
            throw JSONRenderBridgeError(exception: exception)
        }
        guard let returned, returned.isString, let text = returned.toString() else {
            throw JSONRenderBridgeError.invalidResponse("\(method) returned a non-string value")
        }
        let envelope = try JSONValue(jsonString: text)
        if let error = envelope["error"] {
            throw JSONRenderBridgeError.javaScript(
                message: error["message"]?.stringValue ?? "Unknown JavaScript error",
                stack: error["stack"]?.stringValue
            )
        }
        return envelope["result"] ?? .null
    }
}

/// Component and action names declared by the catalog.
public struct CatalogManifest: Sendable, Hashable, Decodable {
    public var components: [String]
    public var actions: [String]
}

/// Result of ``JSONRenderBridge/validateSpec(_:)``.
public struct SpecValidation: Sendable, Hashable, Decodable {
    public struct Issue: Sendable, Hashable, Decodable {
        /// `"error"` or `"warning"`.
        public var severity: String
        public var message: String
        /// JSON Pointer into the spec, when known.
        public var path: String?
        public var code: String?

        public var isError: Bool { severity == "error" }

        public init(severity: String, message: String, path: String? = nil, code: String? = nil) {
            self.severity = severity
            self.message = message
            self.path = path
            self.code = code
        }
    }

    public var valid: Bool
    public var issues: [Issue]

    public init(valid: Bool, issues: [Issue]) {
        self.valid = valid
        self.issues = issues
    }
}

public enum JSONRenderBridgeError: Error, LocalizedError, Sendable, Equatable {
    case resourceMissing
    case bridgeUnavailable
    case javaScript(message: String, stack: String?)
    case invalidResponse(String)

    init(exception: JSValue) {
        let message = exception.toString() ?? "Unknown JavaScript exception"
        let stack = exception.objectForKeyedSubscript("stack")?.toString()
        self = .javaScript(message: message, stack: stack == "undefined" ? nil : stack)
    }

    public var errorDescription: String? {
        switch self {
        case .resourceMissing: "json-render-bridge.js is missing from the JSONRenderSwiftUI bundle"
        case .bridgeUnavailable: "The JavaScript bridge did not install globalThis.JSONRenderBridge"
        case .javaScript(let message, _): "JavaScript error: \(message)"
        case .invalidResponse(let detail): "Invalid bridge response: \(detail)"
        }
    }
}

extension JSONValue {
    func decoded<T: Decodable>(as type: T.Type) throws -> T {
        try JSONDecoder().decode(T.self, from: JSONEncoder().encode(self))
    }
}
