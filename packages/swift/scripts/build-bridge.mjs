// Bundles src/bridge.ts into a self-contained IIFE for JavaScriptCore and copies it
// into the Swift package's resources.
import { build } from "esbuild";
import { copyFile, mkdir, readFile, stat } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoDir = join(packageDir, "..", "..");
const outfile = join(packageDir, "dist", "json-render-bridge.js");
const swiftResource = join(
  repoDir,
  "swift/JSONRender/Sources/JSONRenderSwiftUI/Resources/json-render-bridge.js",
);

const pkg = JSON.parse(
  await readFile(join(packageDir, "package.json"), "utf8"),
);
const corePkg = JSON.parse(
  await readFile(
    join(packageDir, "node_modules/@json-render/core/package.json"),
    "utf8",
  ),
);

// JavaScriptCore contexts have no console unless the host installs one.
// The /*! license notice must stay first; esbuild emits the banner verbatim (outside
// minification), so it survives `legalComments: "none"`.
const licenseNotice =
  "/*! json-render for Swift bridge bundle. Includes @json-render/core and @json-render/react-pdf (Apache-2.0, Copyright 2025 Vercel Inc.) and zod (MIT, Colin McDonnell). See THIRD_PARTY_NOTICES.md. */";

const banner = `${licenseNotice}
/* @json-render/swift ${pkg.version} (core ${corePkg.version}) - JavaScriptCore bridge. Generated by scripts/build-bridge.mjs; do not edit. */
if (typeof globalThis.console === "undefined") {
  globalThis.console = (function () {
    var noop = function () {};
    return { log: noop, info: noop, warn: noop, error: noop, debug: noop };
  })();
}`;

// `import { z } from "zod"` materialises zod's whole namespace, including ~250 KB of
// error-message locales. Only English is ever configured (zod's default), so drop the rest.
const zodEnglishOnly = {
  name: "zod-english-only",
  setup(b) {
    b.onLoad(
      { filter: /[\\/]zod[\\/]v4[\\/]locales[\\/]index\.js$/ },
      (args) => ({
        contents: 'export { default as en } from "./en.js";',
        resolveDir: dirname(args.path),
        loader: "js",
      }),
    );
  },
};

const result = await build({
  entryPoints: [join(packageDir, "src/bridge.ts")],
  outfile,
  bundle: true,
  format: "iife",
  platform: "neutral",
  mainFields: ["module", "main"],
  target: "safari18",
  minify: !process.argv.includes("--no-minify"),
  legalComments: "none",
  metafile: true,
  banner: { js: banner },
  define: {
    "process.env.NODE_ENV": '"production"',
    __BRIDGE_VERSION__: JSON.stringify(pkg.version),
  },
  plugins: [zodEnglishOnly],
  logLevel: "warning",
});

await mkdir(dirname(swiftResource), { recursive: true });
await copyFile(outfile, swiftResource);

const { size } = await stat(outfile);
const inputs = Object.entries(
  result.metafile.outputs[relative(process.cwd(), outfile)]?.inputs ?? {},
);
const byPackage = new Map();
for (const [path, { bytesInOutput }] of inputs) {
  const match = path.match(
    /node_modules\/(?:\.pnpm\/[^/]+\/node_modules\/)?((?:@[^/]+\/)?[^/]+)/,
  );
  const name = match ? match[1] : "src";
  byPackage.set(name, (byPackage.get(name) ?? 0) + bytesInOutput);
}
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`bridge: ${relative(repoDir, outfile)} ${kb(size)}`);
for (const [name, bytes] of [...byPackage].sort((a, b) => b[1] - a[1])) {
  console.log(`  ${name.padEnd(20)} ${kb(bytes)}`);
}
console.log(`copied to ${relative(repoDir, swiftResource)}`);
